export function getAppealGuidance(section: SectionKey): string {
  const patterns = PATTERNS[section]
  if (!patterns) return ''

  return `\n\n## Наблюдения из апелляций по этому разделу
${patterns.map((pattern) => `- ${pattern}`).join('\n')}

В исходной шкале признаки уровня перечислены через «и/или»: оцени общий уровень работы, а не требуй механического выполнения каждого признака одновременно. Это примеры типичных причин замечаний, а не дополнительные критерии или фиксированные штрафы. Применяй их только там, где видишь подтверждение в текущей работе. Не переноси факты из чужих работ, не копируй шаблонные ответы апелляционной комиссии и не придумывай решение комиссии. Балл выбирай по шкале раздела.`
}
